/**
 * Диалоги — пусто, экран проектируется заново.
 *
 * Снято дважды и по одной причине. Сначала полный инбокс: список веток с
 * поиском, фильтрами и меню строки, а справа переписка с паузой ассистента и
 * отправкой сообщения (коммит `2702991`). Затем правая полоса со списком
 * разговоров — строка с именем, последней репликой, временем и меню
 * «закрепить / удалить» (коммит `88385af`). Обе версии целы в истории git.
 *
 * **Бэкенд под экраном цел и работает.** `conversations` и `messages`, правило
 * «написал человек — ассистент в этой ветке замолчал», архив, звёзды, счётчик
 * непрочитанного, поиск по имени, номеру и тексту сообщений — всё на месте, и
 * `lib/api.js` держит вызовы. Главная уже читает `GET /conversations` для двух
 * карточек ассистента, так что данные видны и без этого экрана.
 *
 * **Чего не хватает, чтобы экран имел смысл:** входящих. Вебхука WhatsApp нет,
 * исходящего канала нет, подписи Meta никто не проверяет, а
 * `POST /conversations/ingest` авторизован владельцем — не то место, куда
 * приходит вебхук. Пока их нет, любой инбокс здесь показывает пустоту.
 *
 * **Маршрут остаётся зарегистрированным**, и в навигации остаётся «Диалоги»:
 * пустая страница — честный ответ, 404 — нет.
 */
