/**
 * Контур папки.
 *
 * **Один путь, а не два наложенных прямоугольника.** Через `div`-ы язычок и
 * тело стыкуются под прямым углом, и переход выходит тупым уступом — ровно то,
 * чего здесь быть не должно. Правый край язычка обязан уходить вниз наклоном и
 * входить в верхнюю грань тела плавно, со скруглением на обоих концах наклона,
 * а это кривая: описать её можно только контуром.
 *
 * Заодно контур снимает то, ради чего раньше приходилось изворачиваться:
 * силуэт один, внутреннего стыка нет, поэтому неоткуда взяться шву и незачем
 * подменять тень `drop-shadow` на обёртке.
 *
 * Слева направо: скруглённый верхний левый угол, верхняя грань язычка, вход в
 * наклон, наклон, выход из наклона на верхнюю грань тела, дальше обычный
 * прямоугольник со скруглениями. Наклон занимает около десятой доли ширины —
 * достаточно, чтобы читаться переходом, и мало, чтобы язычок не превратился в
 * треугольник.
 */
const FOLDER_PATH = `
  M 24 0
  L 140 0
  Q 154 0 165 8
  L 199 33
  Q 210 41 224 41
  L 376 41
  Q 400 41 400 65
  L 400 276
  Q 400 300 376 300
  L 24 300
  Q 0 300 0 276
  L 0 24
  Q 0 0 24 0
  Z
`

/**
 * Карточка в виде папки.
 *
 * **`viewBox` 400×300 и `h-auto`.** Пропорция живёт в самом контуре, а не в
 * `aspect-[4/3]` на обёртке: у фигуры со скруглениями стороны нельзя тянуть
 * независимо — углы поплывут. Так карточка масштабируется целиком и остаётся
 * собой на любой ширине.
 *
 * **Заливка — `surface-raised`.** Тот самый случай, ради которого токен и
 * заведён: `surface` на тёмной теме — тот же чёрный, что и фон, и папка без
 * рамки была бы ничем. Заливка отделяет фигуру от фона в обеих темах, поэтому
 * обводка не нужна.
 *
 * Внутри пусто: содержимое появится, когда будет решено, что папка означает.
 */
function Folder({ className = '' }) {
  return (
    <svg
      viewBox="0 0 400 300"
      // Фигура декоративная: читать в ней нечего, и озвучивать тоже.
      aria-hidden="true"
      className={`h-auto ${className}`}
    >
      {/* Через атрибут, а не классом: `fill-*` Tailwind соберёт только для
          зарегистрированного цвета, а обращение к переменной надёжнее прямо
          здесь — и видно, какой именно токен рисует фигуру. */}
      <path d={FOLDER_PATH} fill="var(--color-surface-raised)" />
    </svg>
  )
}
