import { useT } from '../lib/i18n'
import styles from '../styles/Inbox.module.css'

/**
 * Диалоги — пусто, экран проектируется заново.
 *
 * Снято дважды и по одной причине. Сначала полный инбокс: список веток с
 * поиском, фильтрами и меню строки, а справа переписка с паузой ассистента и
 * отправкой сообщения (коммит `2702991`). Затем правая полоса со списком
 * разговоров — строка с именем, последней репликой, временем и меню
 * «закрепить / удалить» (коммит `88385af`). Обе версии целы в истории git.
 *
 * **Бэкенд под экраном цел и работает.** `conversations` и `messages`, правило
 * «написал человек — ассистент в этой ветке замолчал», архив, звёзды, счётчик
 * непрочитанного, поиск по имени, номеру и тексту сообщений — всё на месте, и
 * `lib/api.js` держит вызовы. Главная уже читает `GET /conversations` для двух
 * карточек ассистента, так что данные видны и без этого экрана.
 *
 * **Чего не хватает, чтобы экран имел смысл:** входящих. Вебхука WhatsApp нет,
 * исходящего канала нет, подписи Meta никто не проверяет, а
 * `POST /conversations/ingest` авторизован владельцем — не то место, куда
 * приходит вебхук. Пока их нет, любой инбокс здесь показывает пустоту.
 *
 * **Маршрут остаётся зарегистрированным**, и в навигации остаётся «Диалоги»:
 * пустая страница — честный ответ, 404 — нет.
 */
/**
 * Ряд из четырёх квадратов.
 *
 * **Сторона считается от ширины, а не от высоты, и число карточек задано.**
 * Обратный порядок — квадрат в половину высоты экрана, сколько влезет — даёт
 * неустойчивый ряд: на 1440×900 помещаются три, на 1366×768 четыре, и при
 * растягивании окна карточки перескакивают из ряда в ряд. Так выходит потому,
 * что размер брался от высоты, а вместимость решает ширина, — две величины,
 * никак не связанные между собой.
 *
 * Фиксируем число: `flex-1` делит ряд поровну, `aspect-square` выводит из доли
 * высоту. Сторона тогда сама держится около половины экрана на всех обычных
 * окнах — 52% на 1920×1080, 49% на 1440×900, 58% на 1366×768 — без прыжков.
 *
 * `min-w-0`: элемент flex не сжимается меньше своего содержимого без него, и
 * первая же длинная строка внутри сломает и доли, и квадрат.
 *
 * На телефоне четыре квадрата в ряд — это 80 пикселей на карточку, то есть не
 * карточка. Ниже `sm` они встают в столбец и остаются квадратами по ширине
 * экрана.
 */
function Card() {
  // Без рамки: `surface-raised` — белый на светлой теме и на ступень выше
  // чёрного на тёмной, то есть заливка, которая сама отделяет блок от фона.
  // Рамка поверх неё — обводка вокруг фигуры, у которой край уже есть. Та же
  // карточка, что на главной.
  return (
    <div className="aspect-square w-full min-w-0 rounded-2xl bg-surface-raised sm:flex-1" />
  )
}

function Row() {
  return (
    <div className="flex flex-col gap-4 sm:flex-row sm:gap-6">
      {Array.from({ length: 4 }, (_, index) => (
        <Card key={index} />
      ))}
    </div>
  )
}

export default function InboxPage() {
  const t = useT()

  return (
    <div className={styles.page} aria-label={t('nav.inbox')}>
      {/* Между рядами тот же зазор, что между карточками в ряду: одна величина
          по обеим осям — сетка, разные — две сетки, наложенные друг на друга. */}
      <div className="flex flex-col gap-4 p-4 sm:gap-6 sm:p-6">
        <Row />
        <Row />
      </div>
    </div>
  )
}
