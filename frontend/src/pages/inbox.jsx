/**
 * Карточка в виде папки — язычок сверху слева, тело под ним.
 *
 * **Две части, а не одна с `clip-path`.** Полигон не умеет скруглять углы, а
 * скругление здесь несёт смысл: это карточка того же семейства, что и все
 * остальные в приложении, просто другой формы. Части перекрываются по высоте,
 * поэтому шва между ними нет — обе залиты одним цветом.
 *
 * **Тень — `drop-shadow` на обёртке, а не `box-shadow` на частях.** Фильтр
 * обводит силуэт целиком, а `box-shadow` обвёл бы каждый прямоугольник
 * отдельно и нарисовал линию ровно там, где они стыкуются. Значение не
 * переписано из «покоящейся» карточки дословно: там две тени, а фильтр берёт
 * одну и не знает `spread`, — поэтому взята широкая мягкая половина, а
 * прозрачность приспущена вместо отрицательного разлёта.
 *
 * **Заливка — `surface-raised`.** Это тот самый случай, ради которого токен и
 * заведён: `surface` на тёмной теме — тот же чёрный, что и фон, и папка без
 * рамки была бы ничем. Рамку сюда добавить нельзя — она пройдёт по внутреннему
 * стыку, — поэтому отделять от фона должна именно заливка, а она отделяет в
 * обеих темах.
 *
 * Внутри пусто: содержимое появится, когда будет решено, что папка означает.
 */
function Folder({ className = '' }) {
  return (
    <div
      className={`relative aspect-[4/3] drop-shadow-[0_6px_16px_rgba(23,18,21,0.08)] ${className}`}
    >
      {/* Язычок. Ширина в процентах, а не в пикселях: карточка меняет размер
          вместе с окном, а язычок должен оставаться её частью, а не деталью
          фиксированного размера на растянутой фигуре. */}
      <span className="absolute top-0 left-0 h-[16%] w-[40%] rounded-t-xl bg-surface-raised" />
      {/* Тело. Начинается выше низа язычка — перекрытие и прячет шов. */}
      <span className="absolute inset-x-0 top-[11%] bottom-0 rounded-2xl bg-surface-raised" />
    </div>
  )
}
