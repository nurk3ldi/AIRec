import { useT } from '../lib/i18n'
import styles from '../styles/Inbox.module.css'

/**
 * Диалоги — пусто, экран проектируется заново.
 *
 * Здесь был полный инбокс: список веток с поиском, фильтрами и меню строки
 * (закрепить / архив / удалить), а справа — переписка с паузой ассистента и
 * отправкой сообщения. Снят целиком 2026-09-01; всё это есть в истории git,
 * коммит `2702991` и раньше.
 *
 * **Бэкенд под ним цел и работает.** `conversations` и `messages`, правило
 * «написал человек — ассистент в этой ветке замолчал», архив, звёзды, счётчик
 * непрочитанного, поиск по имени, номеру и тексту сообщений — всё на месте, и
 * `lib/api.js` держит вызовы. Главная уже читает `GET /conversations` для двух
 * карточек ассистента, так что данные видны и без этого экрана.
 *
 * **Чего не хватает, чтобы экран имел смысл:** входящих. Вебхука WhatsApp нет,
 * исходящего канала нет, подписи Meta никто не проверяет, а
 * `POST /conversations/ingest` авторизован владельцем — не то место, куда
 * приходит вебхук. Пока их нет, любой инбокс здесь показывает пустоту.
 *
 * **Маршрут остаётся зарегистрированным**, и в навигации остаётся «Диалоги»:
 * пустая страница — честный ответ, 404 — нет.
 */
export default function InboxPage() {
  const t = useT()

  return (
    // **Определённая высота, а не минимальная**, ровно как на `/appointments` и
    // как было здесь раньше: обе колонки будут прокручиваться каждая у себя, а
    // измерить ребёнка можно только относительно высоты, которая определена.
    // Под `min-height` цепочка flex имеет неопределённый поперечный размер,
    // каждый `flex-1` внутри разрешается в собственное содержимое, и страница
    // отращивает полосу прокрутки вместо того, чтобы её отрастил список.
    //
    // Числа — те же, что в модуле, записанные второй раз настоящей высотой:
    // 68px шапки плюс 50px нижней панели и домашний индикатор под ней до `sm`,
    // и одна шапка от `sm`. Двигать их нужно вместе.
    <div
      className={`${styles.page} flex h-[calc(100vh-118px-env(safe-area-inset-bottom))] overflow-hidden sm:h-[calc(100vh-68px)]`}
      aria-label={t('nav.inbox')}
    >
      {/* Слева — то, ради чего экран: сами разговоры. Пока пусто. */}
      <div className="min-w-0 flex-1" />

      {/* **Линия — это край правой полосы, а не отдельный элемент.**
          `border-l` на самой панели держится за неё при любой её ширине; линия,
          нарисованная отдельно, — третий предмет в ряду, который придётся
          двигать всякий раз, когда меняется доля.

          **Ширина та же, что у правой панели `/appointments`** — 300px плюс её
          собственные `p-4`, записанные суммой, чтобы две величины не разошлись.
          Доля вроде 30% этого не даёт: на широком мониторе она разносит панель
          вдвое шире, чем на ноутбуке, хотя лежать в ней будет одно и то же.
          Фиксированное число — обещание, что на обоих экранах это одна и та же
          полоса, а разговорам слева достаётся всё, что осталось.

          `shrink-0` не даёт flex съесть её, когда слева окажется что-то широкое.

          Ниже `sm` полосы нет: на телефоне она была бы не колонкой, а щелью.
          Что там будет вместо неё, решается отдельно — как и на
          `/appointments`, где телефон получил свой собственный экран. */}
      <aside className="hidden w-[calc(300px+2rem)] shrink-0 border-l border-line sm:block" />
    </div>
  )
}
