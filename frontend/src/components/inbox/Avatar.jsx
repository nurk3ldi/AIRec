import { HugeiconsIcon } from '@hugeicons/react'

/**
 * Кружок со значком того, кто говорит: рядом с репликой в треде и в строке
 * «Потоков».
 *
 * **Вынесен из `Thread`, потому что читателей стало двое**, и две копии кружка
 * совпадали бы ровно до первой правки одной из них.
 *
 * **Один на обе стороны.** Геометрия здесь одна — 40px, ровно высота пузыря в
 * одну строку (14px текста с `leading-snug` плюс `py-2.5`), поэтому кружок
 * стоит вровень с репликой, а не выглядит значком, приставленным сбоку; на
 * длинной реплике пузырь выше, и кружок держится её низа. Две копии этого
 * совпадали бы ровно до первой правки одной из них.
 *
 * **Значок белый (`text-ink`), а не серый.** Серым он читался как подпись —
 * что-то про реплику, а не тот, кто её сказал.
 *
 * **Заливка — `bg-ink/12`, та же, что у круглых кнопок продукта, а не
 * `surface-chip`.** Тот токен на светлой теме — чистый белый, и на белой
 * карточке «Потоков» и белой панели треда кружка не было вовсе: значок висел в
 * пустоте. Ink на 12% — светло-серый круг на белом и тёмно-серый на чёрном, то
 * есть видимый в обеих темах, и заодно одного цвета с `StepButton` рядом.
 *
 * **`invisible`, а не отсутствие**, когда реплика не последняя в серии: место
 * держится у всей серии, иначе пузыри одного автора встали бы по разным краям.
 */
export default function Avatar({ icon, shown = true }) {
  return (
    <span
      aria-hidden="true"
      className={`grid h-10 w-10 shrink-0 place-items-center rounded-full bg-ink/12 text-ink ${
        shown ? '' : 'invisible'
      }`}
    >
      <HugeiconsIcon icon={icon} size={18} strokeWidth={2} />
    </span>
  )
}
