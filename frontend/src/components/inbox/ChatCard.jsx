import { HugeiconsIcon } from '@hugeicons/react'
import { MoreHorizontalIcon } from '@hugeicons/core-free-icons'
import { formatPrice } from '../../lib/appointments'
import { getLocale } from '../../lib/i18n'

/**
 * Один разговор — карточкой, а не строкой списка.
 *
 * Квадрат: сторона выводится из ширины доли (`aspect-square`), а не задаётся в
 * пикселях, поэтому карточка держит форму на любом окне.
 *
 * **Слева вверху: номер, под ним имя.** Порядок не случайный. Номер — то, чем
 * человек опознан в самом канале: он есть всегда, он один и тот же между
 * разговорами, и именно по нему находят прошлые визиты. Имя — то, что клиент
 * сказал о себе, и его может не быть вовсе; тогда вторая строка просто не
 * рисуется, а не превращается в «Без имени», которое сообщает меньше, чем
 * номер строкой выше.
 *
 * Верхний левый угол — там, где начинается чтение, поэтому там стоит то, что
 * отвечает на «чей это разговор».
 *
 * **В середине — запись, к которой разговор привёл.** Это итог: ассистент
 * существует ради неё, и, просматривая инбокс, владелец спрашивает у каждой
 * карточки ровно одно — обернулось ли это записью. Ради такого ответа квадрат и
 * стоит своего места: строка списка его не вместит.
 *
 * **Записи нет — блок не рисуется вовсе.** «Пока не записан» на восьми
 * карточках подряд — это восемь строк, сообщающих отсутствие; пустое место
 * говорит то же самое и молча.
 *
 * **Связи в базе пока нет.** Ни у `conversations` нет `appointment_id`, ни у
 * `appointments` — `conversation_id`; ниже данные приходят из демо-блока
 * страницы. Правильная сторона для ключа — `appointments.conversation_id`: один
 * разговор за месяцы порождает несколько записей (клиент записывается снова в
 * той же ветке), а запись приходит самое большее из одного разговора.
 */
export default function ChatCard({ chat, className = '' }) {
  return (
    // Без рамки: `surface-raised` — белый на светлой теме и на ступень выше
    // чёрного на тёмной, то есть заливка, которая сама отделяет блок от фона.
    // Рамка поверх неё — обводка вокруг фигуры, у которой край уже есть.
    <article
      className={`flex aspect-square min-w-0 flex-col rounded-2xl bg-surface-raised p-5 ${className}`}
    >
      {/* Верхняя строка: кто это — слева, действия над карточкой — справа.

          Три точки, а не сетка из девяти (`More02`): девять точек означают
          «все приложения», а не «действия над этим». Пока кнопка ничего не
          открывает — меню появится, когда будет чему в нём быть. */}
      <div className="flex items-start justify-between gap-3">
        <div className="min-w-0">
        {/* Обе строки в `ink`, а не имя в `muted`: это одно и то же — кто это,
            — сказанное дважды, а не факт и приписка к нему. Разводит их вес, а
            не цвет: номер полужирный, имя обычным начертанием.

            Отрицательный трекинг на номере — крупный текст читается
            разреженным, если его не поджать; на 15px это уже не нужно. */}
          <p className="truncate font-display text-[17px] leading-tight font-semibold tracking-[-0.01em] text-ink">
            {chat.client_phone}
          </p>
          {chat.client_name && (
            <p className="mt-1 truncate text-[15px] leading-tight text-ink">
              {chat.client_name}
            </p>
          )}
        </div>

        <button
          type="button"
          className="-mt-1 -mr-1 grid h-8 w-8 shrink-0 place-items-center rounded-lg text-ink outline-none transition-[background-color,scale] duration-150 ease-out hover:bg-ink/6 focus-visible:bg-ink/6 active:scale-[0.95]"
        >
          <HugeiconsIcon icon={MoreHorizontalIcon} size={18} strokeWidth={2} />
        </button>
      </div>

      {/* Прижата к середине: сверху — кто, снизу останется место под состояние
          и время. Растёт из обеих сторон, поэтому не съезжает, когда у карточки
          одна строка имени вместо двух. */}
      {chat.booking && <Booking booking={chat.booking} />}
    </article>
  )
}

/**
 * Что было записано.
 *
 * **Время — крупное и отдельное, с обоими концами.** Это единственное на
 * карточке, что нужно прочитать издалека: у остального можно задержаться, а
 * «когда» либо видно сразу, либо карточка бесполезна. Обе границы, а не одна:
 * начало без конца — половина факта, и владельцу приходится вспоминать, сколько
 * длится услуга.
 *
 * `tabular-nums` — чтобы «9:00 — 9:45» и «15:00 — 16:00» стояли одной ширины и
 * блок не дёргался между карточками.
 *
 * **Разделители, а не отступы.** Горизонтальная линия отделяет «когда» от «что
 * и почём», вертикальная — одно от другого. Воздух сказал бы то же самое
 * слабее: на карточке, где всё одного цвета, линия — единственное, что задаёт
 * структуру.
 *
 * **Прижат вправо и поднят под шапку.** Правый край — потому что слева уже
 * стоит, чей это разговор: две колонки, каждая со своим краем, вместо одной
 * ленты по центру. Вверх — потому что по центру карточки над блоком оставалась
 * полоса пустоты, которая ничего не разделяла; воздух внизу, где ещё встанут
 * состояние и время, работает, а воздух посередине просто был.
 *
 * **Всё в `ink`.** Ни одна строка здесь не приписка к другой: услуга, цена и
 * время — три равноправные части одного факта.
 *
 * Дата и время через `Intl` с текущей локалью, а не собранные руками: месяц в
 * казахском и русском склоняется по-разному, и таблица на три языка разошлась
 * бы с первой же правкой.
 */
function Booking({ booking }) {
  const from = new Date(booking.starts_at)
  const to = booking.ends_at ? new Date(booking.ends_at) : null

  const clock = (date) =>
    date.toLocaleTimeString(getLocale(), { hour: '2-digit', minute: '2-digit' })

  return (
    <div className="mt-5 flex min-w-0 flex-col">
      <p className="truncate text-right text-[13px] text-ink">
        {from.toLocaleDateString(getLocale(), {
          day: 'numeric',
          month: 'long',
        })}
      </p>

      <p className="mt-1 truncate text-right font-display text-[24px] leading-tight font-semibold tracking-[-0.02em] text-ink tabular-nums">
        {clock(from)}
        {to && ` — ${clock(to)}`}
      </p>

      {/* Линия во всю ширину — она делит карточку, а не строку; сами ячейки
          прижаты вправо, к тому же краю, что и всё выше. */}
      <div className="mt-4 flex min-w-0 items-center justify-end divide-x divide-line border-t border-line pt-4">
        <p className="min-w-0 truncate pr-3 text-right text-[15px] text-ink">
          {booking.service_name}
        </p>
        <p className="shrink-0 pl-3 text-right text-[15px] text-ink">
          {formatPrice(booking.price)}
        </p>
      </div>
    </div>
  )
}
