/**
 * Как в этом продукте выглядит карточка, лежащая на странице.
 *
 * **`surface-raised` и хайрлайн вместе, а не одно вместо другого.** Заливка
 * отделяет карточку от страницы там, где та светлая; на тёмной теме
 * `surface-raised` — это `#171717` на чистом чёрном, и разница есть, но её
 * приходится искать. Линия достраивает край, и вместе они дают ту самую
 * карточку, у которой видно, где она кончается.
 *
 * **`border-line`, а не подобранный серый.** В тёмной теме это `#454545` —
 * значение, взятое в этот проект из вercel'овского `--ds-gray-500`, то есть
 * ровно та граница, на которую тут и ссылаются как на образец. В светлой это
 * серый на 24%, потому что на белой странице тот же цвет читался бы как рамка
 * вокруг всего.
 *
 * **Границу носят карточки, лежащие *на странице*, и только они.** Всё, что
 * нарисовано *на* чём-то другом — запись на сетке расписания, строка в списке,
 * результат поиска, — держит `surface-card` и остаётся без края: под ними уже
 * есть либо линии сетки, либо края панели, и вторая рамка была бы рамкой вокруг
 * рамки. Это же различие записано в таблице токенов в `CLAUDE.md`.
 */
// **A soft edge on continuous corners** (2026-09-13). The edge is Vercel's
// `card-edge`, white at 14% / black at 8% — the solid `#454545` hairline read as
// a hard bright ring. The corner is a 20px squircle (`corner-smooth`): a
// squircle of the same radius looks tighter than a circle, so it is drawn
// larger, and where `corner-shape` is unsupported the 20px circle is the
// fallback.
export const CARD_EDGE = 'rounded-[20px] corner-smooth border border-card-edge bg-surface-raised'

/**
 * Тот же край плюс внутренний отступ и обрезка — крой карточек `/appointments`.
 *
 * **Отдельно от `CARD_EDGE`, потому что отступ у карточек разный**: три над
 * сеткой и карточки «Ассистента» живут на `p-4`, панель «Диалогов» на `p-5`,
 * карточки главной на `p-6`. Общее у них — край, и общей должна быть ровно эта
 * часть; вшить сюда `p-4` значило бы, что half экранов не сможет взять строку
 * целиком и заведёт свою копию.
 *
 * `overflow-hidden` — часть кроя, а не украшение: без него содержимое
 * прямоугольное и углы скругления обрезают не его, а видимость.
 *
 * Носят её три карточки над сеткой «Записей» — «Сейчас», «Дальше», «Ближайшее
 * окно» — и скелет, который стоит на их месте, пока их читают. Скелет,
 * разошедшийся с карточкой хоть на пиксель, — это прыжок раскладки в момент,
 * когда данные приехали.
 */
export const CARD = `${CARD_EDGE} overflow-hidden p-4`
